// 时序之子 · 网页构建：把 win32/web 下的源文件内联成单个 index.html。
// 没有 npm、没有打包器；CSP 不允许外部资源，所以只能内联。
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
const web = path.resolve('win32/web');
const css = ['tokens.css', 'base.css', 'components.css', 'directions.css', 'screens.css', 'directions2.css', 'themes.css', 'release-ui.css'];
const js = ['core.js', 'setup.js', 'screens.js', 'directions.js', 'tide-line.js', 'pages/today.js', 'pages/watch.js', 'pages/records.js', 'pages/stuck.js', 'pages/her.js', 'pages/help.js', 'pages/tide.js', 'pages/settings.js', 'onboarding.js', 'app.js'];
const read = f => fs.readFileSync(path.join(web, f), 'utf8').replace(/\s+$/, '');
// 主题美术资源：源图放在 art/themes/*.jpg，构建时内联成 data URI（CSP 不允许外部请求）。
const artDir = path.resolve('art/styles');
const BLANK = 'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';
const art = name => BLANK; // Theme backgrounds use CSS; no private legacy artwork.
const assetUrl=file=>file+'?v='+createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0,16);
const styleArt = Object.fromEntries(['seer','array','barrier','tower','folio'].map(id=>[id,Object.fromEntries(['hero','empty','icon'].map(kind=>[kind,assetUrl('art/styles/'+id+'-'+kind+'.webp')]))]));
const characterArt=Object.fromEntries(['hero','avatar'].map(k=>[k,assetUrl('art/character/'+k+'.webp')]));
const assets=[...Object.values(styleArt).flatMap(v=>Object.values(v)),...Object.values(characterArt)];
fs.writeFileSync('win32/res/art_auto.rc',assets.map((f,i)=>(201+i)+' RCDATA "../'+f.split('?')[0]+'"').join('\n')+'\n');
fs.writeFileSync('win32/src/art_resources.h','#pragma once\n// Generated by build-web.mjs; exact embedded asset allowlist.\ninline int WebArtResource(const std::wstring& url){\n'+assets.map((f,i)=>'    if(url==std::wstring(BRAND_ORIGIN)+L"'+f+'")return '+(201+i)+';').join('\n')+'\n    return 0;\n}\n');
const brandHeader = fs.readFileSync('win32/src/brand.h','utf8');
const brandValue = key => JSON.parse('"'+brandHeader.match(new RegExp('^#define '+key+' L?"([^"\\n]*)"','m'))[1]+'"');
const brand = {name:brandValue('BRAND_NAME'),id:brandValue('BRAND_ID'),hermes:brandValue('BRAND_HERMES'),keeper:brandValue('BRAND_KEEPER'),rift:brandValue('BRAND_RIFT_NAME')};
let html = fs.readFileSync(path.join(web, 'shell.html'), 'utf8');
let cssText = css.map(read).join('\n\n');
cssText = cssText.replace(/__ART_([A-Z0-9_]+)__/g, (_m, key) => art(key.toLowerCase().replace(/_/g, '-')));
html = html.replace('__BRAND_NAME__', brand.name);
html = html.replace('/*@css*/', () => cssText);
html = html.replace('/*@js*/', () => 'const CHARACTER_ART = '+JSON.stringify(characterArt)+';\nconst STYLE_ART = '+JSON.stringify(styleArt)+';\nconst BRAND = '+JSON.stringify(brand)+';\n'+js.map(read).join('\n\n'));
fs.writeFileSync(path.join(web, 'index.html'), html, 'utf8');
console.log(`[web] ${html.length} bytes, css ${css.length} js ${js.length}`);
